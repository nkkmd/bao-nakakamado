"use strict";
// MIT. Deterministic browser adapter; never reads final rows or changes frozen assets.
const fs = require("node:fs"), path = require("node:path"), assert = require("node:assert/strict");
const F = require("./frozen-model-search.cjs");
const root = path.resolve(__dirname, "../..");
F.preflight();
const bytes = fs.readFileSync(path.join(root, "tools/ai-integration/frozen-models/formal-v1-linear-2026100401/model.json"), "utf8");
const model = F.checkModelBytes(Buffer.from(bytes));
assert.equal(model.kind, "linear");
const input = fs.readFileSync(path.join(__dirname, "learning-input.cjs"), "utf8")
  .replace('const E = require("../../prototype/next-turn-engine.js");', 'const E = root.BaoEngine;')
  .replace('const Q = require("../../prototype/search-transition.js").createForEngine(E);', 'const Q = root.NakakamadoSearchTransition.createForEngine(E);')
  .replace('module.exports={ID,INPUT_SIZE,validate,encode,positionKey,placement};', '');
const generated = `"use strict";
// MIT. Generated by tools/ai-integration/build-browser-model.cjs; do not edit.
// Exact frozen linear model and encoder.
(function(root) {
${input}
const MODEL_BYTES = ${JSON.stringify(bytes)};
const MODEL_SHA256 = "${require('./formal-final-spec.json').candidate.modelSha256}";
const MODEL_ID = "${F.spec.evaluatorId}";
const m = JSON.parse(MODEL_BYTES);
function raw(x) { return x.reduce((n,v,i) => n + v*m.weights[i], m.bias); }
function createEvaluator() {
  function evaluate(s,p=s.player,check=()=>{}) {
    check(); const outcome=Q.outcome(s);
    if(outcome==='safety-stop') return 0;
    if(outcome==='normal-terminal') return s.winner===p ? 1000000 : -1000000;
    const a=raw(encode(s,p)), b=raw(encode(s,1-p)), scale=m.quantizationScale;
    const clip=n=>Math.max(-scale,Math.min(scale,n));
    check(); return Math.trunc(1024*(clip(a)-clip(b))/(2*scale)) || 0;
  }
  return Object.freeze({ID:MODEL_ID, WIN:1000000, evaluate,
    breakdown:(s,p=s.player,check)=>({evaluatorId:MODEL_ID,total:evaluate(s,p,check),outcome:Q.outcome(s)})});
}
async function verifyBytes() {
  const digest=await root.crypto.subtle.digest('SHA-256',new TextEncoder().encode(MODEL_BYTES));
  const actual=Array.from(new Uint8Array(digest),n=>n.toString(16).padStart(2,'0')).join('');
  if(actual!==MODEL_SHA256) throw Error('Frozen model digest mismatch');
}
root.NakakamadoBrowserModel=Object.freeze({MODEL_ID,MODEL_SHA256,createEvaluator,verifyBytes,encode});
}(typeof window !== 'undefined' ? window : globalThis));
`;
const dest = path.join(root, "prototype/browser-model.js");
if (process.argv.includes("--check")) assert.equal(fs.readFileSync(dest,"utf8"), generated, "Regenerate browser-model.js");
else fs.writeFileSync(dest, generated);
console.log(JSON.stringify({status:"PASS", modelSha256: require('./formal-final-spec.json').candidate.modelSha256, generatedBytes:Buffer.byteLength(generated), formalRowsRead:0}));
